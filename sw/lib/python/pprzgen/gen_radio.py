"""Port of sw/tools/generators/gen_radio.ml: generates radio.h"""

from . import env
from .xml2h import open_out
from .ocaml import Failure

H_NAME = "RADIO_H"


def check_function_name(s):
    for ch in s:
        if not (("A" <= ch <= "Z") or ("0" <= ch <= "9") or ch == "_"):
            raise Failure("Character '%s' not allowed in function name '%s'" % (ch, s))


def norm1_ppm(c):
    if c.neutral == c.min or c.neutral == c.max:
        return ("tmp_radio * (MAX_PPRZ / (float)(RC_PPM_SIGNED_TICKS_OF_USEC(%d-%d)))" % (c.max, c.min), "0")
    return ("tmp_radio * (tmp_radio >=0 ? (MAX_PPRZ/(float)(RC_PPM_SIGNED_TICKS_OF_USEC(%d-%d))) : "
            "(MIN_PPRZ/(float)(RC_PPM_SIGNED_TICKS_OF_USEC(%d-%d))))" % (c.max, c.neutral, c.min, c.neutral),
            "MIN_PPRZ")


def gen_normalize_ppm_fir(out, channels):
    out.write("#define NormalizePpmFIR(_ppm, _rc) {\\\n")
    out.write("  static uint8_t avg_cpt = 0; /* Counter for averaging */\\\n")
    out.write("  int16_t tmp_radio;\\\n")
    for c in channels:
        value, min_pprz = norm1_ppm(c)
        if c.average:
            out.write("  _rc.avg_values[RADIO_%s] += _ppm[RADIO_%s];\\\n" % (c.cname, c.cname))
        else:
            out.write("  tmp_radio = _ppm[RADIO_%s] - RC_PPM_TICKS_OF_USEC(%d);\\\n" % (c.cname, c.neutral))
            out.write("  _rc.values[RADIO_%s] = %s;\\\n" % (c.cname, value))
            out.write("  Bound(_rc.values[RADIO_%s], %s, MAX_PPRZ); \\\n\\\n" % (c.cname, min_pprz))
    out.write("  avg_cpt++;\\\n")
    out.write("  if (avg_cpt == RC_AVG_PERIOD) {\\\n")
    out.write("    avg_cpt = 0;\\\n")
    for c in channels:
        if c.average:
            value, min_pprz = norm1_ppm(c)
            out.write("    tmp_radio = _rc.avg_values[RADIO_%s] / RC_AVG_PERIOD -  RC_PPM_TICKS_OF_USEC(%d);\\\n" % (c.cname, c.neutral))
            out.write("    _rc.values[RADIO_%s] = %s;\\\n" % (c.cname, value))
            out.write("    _rc.avg_values[RADIO_%s] = 0;\\\n" % c.cname)
            out.write("    Bound(_rc.values[RADIO_%s], %s, MAX_PPRZ); \\\n\\\n" % (c.cname, min_pprz))
    out.write(" }\\\n")
    out.write("}\n\n")


def norm1_ppm2(c):
    if c.neutral == c.min or c.neutral == c.max:
        return ("(tmp_radio * MAX_PPRZ) / (RC_PPM_SIGNED_TICKS_OF_USEC(%d-%d))" % (c.max, c.min), "0")
    return ("(tmp_radio >=0 ? (tmp_radio *  MAX_PPRZ) / (RC_PPM_SIGNED_TICKS_OF_USEC(%d-%d)) : "
            "(tmp_radio * MIN_PPRZ) / (RC_PPM_SIGNED_TICKS_OF_USEC(%d-%d)))" % (c.max, c.neutral, c.min, c.neutral),
            "MIN_PPRZ")


def gen_normalize_ppm_iir(out, channels):
    out.write("#define NormalizePpmIIR(_ppm, _rc) {\\\n")
    out.write("  int32_t tmp_radio;\\\n")
    out.write("  int32_t tmp_value;\\\n\\\n")
    for c in channels:
        value, min_pprz = norm1_ppm2(c)
        out.write("  tmp_radio = _ppm[RADIO_%s] - RC_PPM_TICKS_OF_USEC(%d);\\\n" % (c.cname, c.neutral))
        out.write("  tmp_value = %s;\\\n" % value)
        out.write("  Bound(tmp_value, %s, MAX_PPRZ); \\\n" % min_pprz)
        if c.average:
            out.write("  _rc.values[RADIO_%s] = (pprz_t)((RADIO_FILTER * _rc.values[RADIO_%s] + tmp_value) / (RADIO_FILTER + 1));\\\n\\\n" % (c.cname, c.cname))
        else:
            out.write("  _rc.values[RADIO_%s] = (pprz_t)(tmp_value);\\\n\\\n" % c.cname)
    out.write("}\n\n")


def generate(radio, xml_file, out_file):
    with open_out(out_file) as out:
        out.write("/* This file has been generated by gen_radio from %s */\n" % xml_file)
        out.write("/* Version %s */\n" % env.get_paparazzi_version())
        out.write("/* Please DO NOT EDIT */\n\n")
        out.write("#ifndef %s\n" % H_NAME)
        out.write("#define %s\n\n" % H_NAME)
        out.write("#define RADIO_NAME %s\n\n" % radio.name)
        out.write("#define RADIO_CTL_NB %d\n\n" % len(radio.channels))
        out.write("#define RADIO_FILTER 7\n\n")
        for i, c in enumerate(radio.channels):
            check_function_name(c.cname)
            out.write("#define RADIO_%s %d\n" % (c.cname, i))
            out.write("#define RADIO_%s_NEUTRAL %d\n" % (c.cname, c.neutral))
            out.write("#define RADIO_%s_MIN %d\n" % (c.cname, c.min))
            out.write("#define RADIO_%s_MAX %d\n\n" % (c.cname, c.max))
            if (not c.reverse and c.max < c.min) or (c.reverse and c.min < c.max):
                raise Failure('Error: "%s" radio channel: max must be superior to min! Use reverse="1" to reverse the channel.' % c.cname)
        out.write("#define PPM_PULSE_TYPE PPM_PULSE_TYPE_%s\n" % radio.pulse_type)
        out.write("#define PPM_DATA_MIN_LEN (%dul)\n" % radio.data_min)
        out.write("#define PPM_DATA_MAX_LEN (%dul)\n" % radio.data_max)
        out.write("#define PPM_SYNC_MIN_LEN (%dul)\n" % radio.sync_min)
        out.write("#define PPM_SYNC_MAX_LEN (%dul)\n\n" % radio.sync_max)
        gen_normalize_ppm_fir(out, radio.channels)
        gen_normalize_ppm_iir(out, radio.channels)
        out.write("\n#endif // %s\n" % H_NAME)

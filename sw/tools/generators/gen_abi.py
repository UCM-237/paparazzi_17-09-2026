#!/usr/bin/env python3
"""ABI messages header generator (Python replacement of gen_abi.out).

Usage: gen_abi.py <abi.xml> <class_name>   (header written on stdout)
"""

import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "lib", "python"))

from pprzgen import xml_light as X, ext_xml, env  # noqa: E402
from pprzgen.ocaml import Failure, NotFound, int_of_string  # noqa: E402


def capitalize(s):
    return s[:1].upper() + s[1:]


def read(filename, class_):
    xml = ext_xml.parse_file(filename)
    try:
        xml_class = ext_xml.child(xml, "msg_class", select=lambda x: X.attrib(x, "name") == class_)
    except NotFound:
        raise Failure("No msg_class '%s' found" % class_)
    msgs = []
    for x in X.children(xml_class):
        name = ext_xml.attrib(x, "name")
        id_ = ext_xml.int_attrib(x, "id")
        fields = [(ext_xml.attrib(f, "name"), ext_xml.attrib(f, "type")) for f in X.children(x)]
        msgs.append((name, id_, fields))
    tab = [False] * 256
    last_id = 0
    for _, id_, _ in msgs:
        if not 0 <= id_ < 256:
            raise IndexError("index out of bounds")
        if tab[id_]:
            raise Failure("Duplicated message id: %d" % id_)
        if id_ < last_id:
            sys.stderr.write("Warning: unsorted id: %d\n" % id_)
            sys.stderr.flush()
        last_id = id_
        tab[id_] = True
    return msgs


def args_decl(fields):
    s = "(uint8_t sender_id"
    for n, t in fields:
        s += ", %s %s" % (t, n)
    return s + ")"


def main(argv):
    if len(argv) != 3:
        raise Failure("Usage: %s <.xml file> <class_name>" % argv[0])
    filename, class_name = argv[1], argv[2]
    messages = read(filename, class_name)
    h = []
    h.append("/* Automatically generated by gen_abi from %s */\n" % filename)
    h.append("/* Version %s */\n" % env.get_paparazzi_version())
    h.append("/* Please DO NOT EDIT */\n\n")
    h.append("/* Onboard middleware library ABI\n")
    h.append(" * send and receive messages of class %s\n" % class_name)
    h.append(" */\n\n")
    h.append("#ifndef ABI_MESSAGES_H\n")
    h.append("#define ABI_MESSAGES_H\n\n")
    h.append('#include "modules/core/abi_common.h"\n')
    h.append("\n/* Messages IDs */\n")
    highest = 0
    for name, id_, _ in messages:
        if id_ > highest:
            highest = id_
        h.append("#define ABI_%s_ID %d\n" % (capitalize(name), id_))
    h.append("\n/* Array and linked list structure */\n")
    h.append("#define ABI_MESSAGE_NB %d\n\n" % (highest + 1))
    h.append("ABI_EXTERN abi_event* abi_queues[ABI_MESSAGE_NB];\n")
    h.append("\n/* Callbacks */\n")
    for name, _, fields in messages:
        h.append("typedef void (*abi_callback%s)%s;\n" % (capitalize(name), args_decl(fields)))
    h.append("\n/* Bind and Send functions */\n")
    for name, _, fields in messages:
        n = capitalize(name)
        h.append("\nstatic inline void AbiBindMsg%s(uint8_t sender_id, abi_event * ev, abi_callback%s cb) {\n" % (n, n))
        h.append("  if (abi_queues[ABI_%s_ID] == ev) return;\n" % n)
        h.append("  ev->id = sender_id;\n")
        h.append("  ev->cb = (abi_callback)cb;\n")
        h.append("  ABI_PREPEND(abi_queues[ABI_%s_ID],ev);\n" % n)
        h.append("}\n")
        h.append("\nstatic inline void AbiSendMsg%s%s" % (n, args_decl(fields)))
        h.append(" {\n")
        h.append("  abi_event* e;\n")
        h.append("  ABI_FOREACH(abi_queues[ABI_%s_ID],e) {\n" % n)
        h.append("    if (e->id == ABI_BROADCAST || e->id == sender_id) {\n")
        h.append("      abi_callback%s cb = (abi_callback%s)(e->cb);\n" % (n, n))
        h.append("      cb(sender_id" + "".join(", %s" % fn for fn, _ in fields) + ");\n")
        h.append("    }\n")
        h.append("  }\n")
        h.append("}\n")
    h.append("\n#endif // ABI_MESSAGES_H\n")
    sys.stdout.buffer.write("".join(h).encode("latin-1"))


if __name__ == "__main__":
    try:
        main(sys.argv)
    except Failure as e:
        sys.stderr.write('Fatal error: exception Failure("%s")\n' % e)
        sys.exit(2)

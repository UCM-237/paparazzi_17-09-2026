#!/usr/bin/env python3
"""MTK protocol header generator (Python replacement of gen_mtk.out).

Usage: gen_mtk.py <mtk.xml>   (header written on stdout)
"""

import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "lib", "python"))

from pprzgen import xml_light as X, ext_xml  # noqa: E402
from pprzgen.ocaml import Failure, int_of_string  # noqa: E402

_out = []


def w(s):
    _out.append(s)


SIZES = {"U4": 4, "I4": 4, "U2": 2, "I2": 2, "U1": 1, "I1": 1, "U4BE": 4, "I4BE": 4, "U2BE": 2, "I2BE": 2}
CTYPES = {"I2": "int16_t", "I4": "int32_t", "U2": "uint16_t", "U4": "uint32_t", "U1": "uint8_t", "I1": "int8_t",
          "I2BE": "int16_t", "I4BE": "int32_t", "U2BE": "uint16_t", "U4BE": "uint32_t"}


def sizeof(f):
    if f not in SIZES:
        raise Failure("sizeof: unknown format '%s'" % f)
    return SIZES[f]


def c_type(f):
    if f not in CTYPES:
        raise Failure("Gen_mtk.c_type: unknown format '%s'" % f)
    return CTYPES[f]


def get_at(o, fmt, block_size):
    t = c_type(fmt)
    b = "" if block_size == 0 else "+%d*_mtk_block" % block_size
    if fmt in ("U4", "I4"):
        return ("(%s)(*((uint8_t*)_mtk_payload+%d%s)|*((uint8_t*)_mtk_payload+1+%d%s)<<8|((%s)*((uint8_t*)_mtk_payload+2+%d%s))<<16|((%s)*((uint8_t*)_mtk_payload+3+%d%s))<<24)"
                % (t, o, b, o, b, t, o, b, t, o, b))
    if fmt in ("U2", "I2"):
        return "(%s)(*((uint8_t*)_mtk_payload+%d%s)|*((uint8_t*)_mtk_payload+1+%d%s)<<8)" % (t, o, b, o, b)
    if fmt in ("U1", "I1"):
        return "(%s)(*((uint8_t*)_mtk_payload+%d%s))" % (t, o, b)
    if fmt in ("U4BE", "I4BE"):
        return ("(%s)(*((uint8_t*)_mtk_payload+3+%d%s)|*((uint8_t*)_mtk_payload+2+%d%s)<<8|((%s)*((uint8_t*)_mtk_payload+1+%d%s))<<16|((%s)*((uint8_t*)_mtk_payload+%d%s))<<24)"
                % (t, o, b, o, b, t, o, b, t, o, b))
    if fmt in ("U2BE", "I2BE"):
        return "(%s)(*((uint8_t*)_mtk_payload+1+%d%s)|*((uint8_t*)_mtk_payload+%d%s)<<8)" % (t, o, b, o, b)
    raise Failure("Gen_mtk.c_type: unknown format '%s'" % fmt)


def define(x, y):
    w("#define %s %s\n" % (x, y))


class LengthError(Exception):
    def __init__(self, m, l1, l2):
        super().__init__(l1, l2)
        self.m, self.l1, self.l2 = m, l1, l2


def parse_message(class_name, m):
    msg_name = X.attrib(m, "name")
    w("\n")
    define("MTK_%s_%s_ID" % (class_name, msg_name), X.attrib(m, "ID"))
    offset = [0]

    def gen(block_size, f):
        t = X.tag(f)
        if t == "field":
            fn = ext_xml.attrib(f, "name")
            fmt = X.attrib(f, "format")
            block_no = "" if block_size == 0 else ",_mtk_block"
            define("MTK_%s_%s_%s(_mtk_payload%s)" % (class_name, msg_name, fn, block_no), get_at(offset[0], fmt, block_size))
            offset[0] += sizeof(fmt)
        elif t == "block":
            s = int_of_string(X.attrib(f, "length"))
            o = offset[0]
            for c in X.children(f):
                gen(s, c)
            if s != offset[0] - o:
                raise LengthError(f, s, offset[0] - o)
        else:
            raise Failure("Unexpected field: " + t)

    for c in X.children(m):
        gen(0, c)
    try:
        l = int_of_string(X.attrib(m, "length"))
        if l != offset[0]:
            raise LengthError(m, l, offset[0])
    except X.NoAttribute as e:
        if str(e) != "length":
            raise
    w("\n#define MTK_%s_%s_LENGTH %d\n" % (class_name, msg_name, offset[0]))


def parse_class(c):
    int_of_string(X.attrib(c, "id"))
    class_name = X.attrib(c, "name")
    w("\n")
    define("MTK_%s_ID" % class_name, X.attrib(c, "ID"))
    for m in X.children(c):
        parse_message(class_name, m)


def main(argv):
    if len(argv) != 2:
        raise Failure("Usage: %s <.xml mtk protocol file>" % argv[0])
    xml_file = argv[1]
    code = 0
    try:
        xml = X.parse_file(xml_file)
        w("/* Generated by gen_mtk from %s */\n" % xml_file)
        w("/* Please DO NOT EDIT */\n\n")
        define("MTK_DIY14_SYNC1", "0xB5")
        define("MTK_DIY14_SYNC2", "0x62")
        for c in X.children(xml):
            parse_class(c)
    except LengthError as e:
        sys.stderr.write('File "%s", inconsistent length: %d expected, %d found from fields in message:\n %s\n'
                         % (xml_file, e.l1, e.l2, X.to_string_fmt(e.m)))
        code = 1
    except X.DtdCheckError as e:
        sys.stderr.write('File "%s", DTD check error: %s\n' % (xml_file, e))
    except X.DtdProveError as e:
        sys.stderr.write('\nFile "%s", DTD check error: %s\n\n' % (xml_file, e))
    sys.stdout.buffer.write("".join(_out).encode("latin-1"))
    sys.stdout.flush()
    if code:
        sys.exit(code)


if __name__ == "__main__":
    try:
        main(sys.argv)
    except Failure as e:
        sys.stdout.buffer.write("".join(_out).encode("latin-1"))
        sys.stderr.write('Fatal error: exception Failure("%s")\n' % e)
        sys.exit(2)
